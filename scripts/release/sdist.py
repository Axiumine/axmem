"""Refuse an sdist that carries files git does not track.

hatchling's sdist target walks the working tree and honours only the root ``.gitignore``, not nested ones and
not ``.git/info/exclude``, and it re-includes a ``!``-negated path even under an excluded directory, which git
never does. Every untracked file that slips past is baked into the tarball PyPI serves, and it is baked in
per machine: CI checks out the tag clean, rebuilds, gets different bytes, and ``release.yml`` refuses to sign.

So this check asserts the invariant a denylist cannot: an sdist may only contain files reachable from the
tag. Anything else is, by construction, not reproducible from a clean checkout, and is usually also junk
nobody wants in a ``pip install``.

    python3 -m scripts.release.sdist --dist dist

It also refuses the one tracked file that can never reproduce: the digest manifest. The release script writes
it after the build and commits it with the tag, so a packed copy is always the previous release's while the
tag's differs, and a manifest of the sdist's digest cannot be an input to that sdist anyway.

Exits non-zero, listing the offenders, when the sdist holds anything that is neither tracked by git (in this
repo or a submodule) nor generated by the build itself, or holds a file the release rewrites after building.
"""

from __future__ import annotations

import argparse
import subprocess  # nosec B404 - runs git, gh, uv and python with fixed argv lists, never a shell
import sys
import tarfile
from pathlib import Path

# the build writes these into the sdist; they are never tracked (hatch-vcs writes the version file)
GENERATED = {"PKG-INFO", "app/_version.py"}

# tracked, but rewritten by scripts/release-pypi.sh AFTER the build and committed with
# the tag — a packed copy is always stale relative to the tag CI rebuilds from.
WRITTEN_AFTER_BUILD = {"release-digests.json"}

# how many offenders to name before collapsing to a count
MAX_LISTED = 25


def _git(*args: str, cwd: Path) -> str:
    """Run a read-only git command, returning stdout (empty string on failure)."""
    proc = subprocess.run(  # nosec B603 B607 - git with fixed arguments, never a shell
        ["git", *args],
        cwd=cwd,
        capture_output=True,
        text=True,
        check=False,
    )
    return proc.stdout if proc.returncode == 0 else ""


def _submodule_prefixes(root: Path) -> list[str]:
    """Paths of the repo's submodules, relative to the repo root."""
    out = _git("submodule", "--quiet", "foreach", "--recursive", "echo $sm_path", cwd=root)
    return [line.strip() for line in out.splitlines() if line.strip()]


def tracked_files(root: Path) -> set[str]:
    """Every path git tracks, this repo plus each submodule, repo-root relative."""
    tracked = {line for line in _git("ls-files", cwd=root).splitlines() if line}
    for prefix in _submodule_prefixes(root):
        sub = root / prefix
        tracked.update(
            f"{prefix}/{line}" for line in _git("ls-files", cwd=sub).splitlines() if line
        )
    return tracked


def sdist_members(sdist: Path) -> set[str]:
    """File paths inside the sdist, with the `<name>-<version>/` prefix stripped."""
    members: set[str] = set()
    with tarfile.open(sdist, "r:gz") as tar:
        for entry in tar:
            if not entry.isfile():
                continue
            _, _, relative = entry.name.partition("/")
            if relative:
                members.add(relative)
    return members


def _find_sdist(dist: Path) -> Path:
    """The single .tar.gz in dist/ — more or fewer than one is a caller error."""
    candidates = sorted(dist.glob("*.tar.gz"))
    if len(candidates) != 1:
        found = ", ".join(p.name for p in candidates) or "none"
        raise SystemExit(f"ERROR: expected exactly one sdist in {dist}, found: {found}")
    return candidates[0]


def _report(sdist: Path, untracked: set[str]) -> None:
    """Print the offenders and what they mean for the release."""
    print(
        f"ERROR: {sdist.name} contains {len(untracked)} file(s) git does not track.",
        file=sys.stderr,
    )
    print("  These cannot exist in a clean checkout of the tag, so CI's rebuild", file=sys.stderr)
    print("  will differ and the signing job will refuse the release.", file=sys.stderr)
    print(
        "  Add them to [tool.hatch.build.targets.sdist] in pyproject.toml.", file=sys.stderr,
    )
    for path in sorted(untracked)[:MAX_LISTED]:
        print(f"    {path}", file=sys.stderr)
    if len(untracked) > MAX_LISTED:
        print(f"    … and {len(untracked) - MAX_LISTED} more", file=sys.stderr)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dist", required=True, help="directory holding the built sdist")
    parser.add_argument("--repo", default=".", help="repo root (default: cwd)")
    args = parser.parse_args(argv)

    root = Path(args.repo).resolve()
    sdist = _find_sdist(Path(args.dist))

    members = sdist_members(sdist)
    stale = sorted(members & WRITTEN_AFTER_BUILD)
    if stale:
        print(
            f"ERROR: {sdist.name} packs {', '.join(stale)}, which the release rewrites",
            file=sys.stderr,
        )
        print(
            "  after building — the tag's copy differs, so CI's rebuild cannot match.",
            file=sys.stderr,
        )
        print(
            "  Add it to [tool.hatch.build.targets.sdist] in pyproject.toml.",
            file=sys.stderr,
        )
        return 1

    untracked = members - tracked_files(root) - GENERATED
    if untracked:
        _report(sdist, untracked)
        return 1

    print(f"OK: every file in {sdist.name} is tracked by git.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
